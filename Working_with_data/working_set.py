# Using curly braces
fruits = {"apple", "banana", "mango"}
print(fruits)

# Using the set() constructor
numbers = set([1, 2, 3, 4])
print(numbers)

# Creating an empty set (must use set(), not{})
empty_set = set()
print(empty_set)

# from a string (duplicates re,oved automatically)
letters = set("mississippi")
print(letters)

# Adding element
colors = {"red", "blue"}
colors.add("green")